import { Constants, type Database, type Tables, type TablesInsert } from './database.types';

type PublicTable = keyof Database['public']['Tables'];

/**
 * Guards the contract between supabase/migrations and the generated types
 * (`npm run db:types`). If this fails, either regenerate the types or update the migration.
 */
describe('database.types', () => {
  it('exposes the public tables', () => {
    const tables: PublicTable[] = [
      'profiles',
      'lesson_progress',
      'xp_events',
      'streaks',
      'review_cards',
      'review_logs',
    ];
    const satisfiesTable: Record<PublicTable, true> = {
      profiles: true,
      lesson_progress: true,
      xp_events: true,
      streaks: true,
      review_cards: true,
      review_logs: true,
    };
    expect(Object.keys(satisfiesTable).sort()).toEqual([...tables].sort());
  });

  it('matches the enum values declared in the migration', () => {
    expect(Constants.public.Enums.cefr_level).toEqual(['A1', 'A2', 'B1', 'B2', 'C1', 'C2']);
    expect(Constants.public.Enums.learning_goal).toEqual(['travel', 'work', 'relocation', 'dele']);
    expect(Constants.public.Enums.spanish_variant).toEqual(['spain', 'latam']);
    expect(Constants.public.Enums.lesson_status).toEqual(['in_progress', 'completed']);
    expect(Constants.public.Enums.xp_source).toEqual([
      'lesson',
      'review',
      'streak_bonus',
      'chat',
      'other',
    ]);
  });

  it('types a profile row and an FSRS card insert as expected', () => {
    const profile: Tables<'profiles'> = {
      id: '11111111-1111-1111-1111-111111111111',
      display_name: null,
      level: 'A1',
      goal: null,
      daily_minutes: 10,
      spanish_variant: 'spain',
      timezone: 'UTC',
      created_at: '2026-10-19T00:00:00Z',
      updated_at: '2026-10-19T00:00:00Z',
    };

    // user_id and item_id are required. direction defaults to recognition.
    const card: TablesInsert<'review_cards'> = {
      user_id: profile.id,
      item_id: 'hola',
    };
    const recall: TablesInsert<'review_cards'> = {
      user_id: profile.id,
      item_id: 'hola',
      direction: 'ru_to_es',
    };

    const review: TablesInsert<'review_logs'> = {
      user_id: profile.id,
      card_id: 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa',
      rating: 3,
      reviewed_at: '2026-10-23T00:00:00Z',
      elapsed_days: 0,
      scheduled_days: 0,
      state: 0,
      client_id: 'rev-1',
    };

    // XP ledger rows never carry an id: it is generated by the database.
    const xp: TablesInsert<'xp_events'> = { user_id: profile.id, amount: 10, source: 'lesson' };

    expect(profile.level).toBe('A1');
    expect(card.item_id).toBe('hola');
    expect(recall.direction).toBe('ru_to_es');
    expect(review.rating).toBe(3);
    expect(xp.amount).toBe(10);
  });
});
